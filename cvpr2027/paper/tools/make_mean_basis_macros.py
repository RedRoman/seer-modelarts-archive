#!/usr/bin/env python3
"""Generate paper macros for the exploratory, unadjusted SDSD VAL16 analysis."""
import argparse
from pathlib import Path
import sys

CVPR = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CVPR / "tools"))
from analyze_mean_basis_val import (  # noqa: E402
    DEFAULT_INPUT, load_validated_analysis, require, serialize, sha256,
)

CONDITIONS = {
    "identity": "identity",
    "meanonly": "clip_mean_only",
    "clipclip": "clip_mean_clip_basis",
    "clipfixed": "clip_mean_training_basis",
    "trainclip": "training_mean_clip_basis",
    "trainfixed": "training_mean_training_basis",
}
CONTRASTS = {
    "rank4vsidentity": ("clip_mean_clip_basis", "identity"),
    "rank4vsmeanonly": ("clip_mean_clip_basis", "clip_mean_only"),
    "clipvsfixed": ("clip_mean_clip_basis", "clip_mean_training_basis"),
    "meanvsfixedmean_clipbasis": ("clip_mean_clip_basis", "training_mean_clip_basis"),
    "meanvsfixedmean_fixedbasis": ("clip_mean_training_basis", "training_mean_training_basis"),
}
METRICS = (("psnr_y", "psnr", 3), ("lpips", "lpips", 4))


def make_macros(analysis):
    macros = {"meanval@n": "16", "meanval@scenes": "8", "meanval@seeds": "2"}
    for short, condition in CONDITIONS.items():
        for metric, label, decimals in METRICS:
            value = analysis["conditions"][condition][metric]
            key = f"meanval@{short}@{label}"
            macros[key] = f"{value['mean']:.{decimals}f}"
            for seed, number in enumerate(value["per_seed"]):
                macros[f"{key}@seed{seed}"] = f"{number:.{decimals}f}"
    for short, (a, b) in CONTRASTS.items():
        for metric, label, decimals in METRICS:
            value = analysis["contrasts"][a + "_minus_" + b][metric]
            key = f"meanval@{short}@{label}"
            macros[key] = f"{value['mean_difference']:+.{decimals}f}"
            for field, suffix in (("sequence_ci95", "seqci"), ("scene_cluster_ci95", "sceneci")):
                lo, hi = value[field]
                macros[f"{key}@{suffix}"] = f"[{lo:+.{decimals}f}, {hi:+.{decimals}f}]"
            macros[f"{key}@seedagree"] = "yes" if value["same_sign_across_seeds"] else "no"
            for seed, number in enumerate(value["per_seed_differences"]):
                macros[f"{key}@seed{seed}"] = f"{number:+.{decimals}f}"
    return macros


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--out", type=Path, default=CVPR / "paper/tables/result_macros_mean_basis.tex")
    parser.add_argument("--check", action="store_true", help="Verify existing macros without writing")
    args = parser.parse_args()
    analysis = load_validated_analysis(args.input_dir)
    analysis_path = args.input_dir / "analysis.json"
    require(analysis_path.read_text() == serialize(analysis), "Stored analysis differs from raw-data recomputation")
    macros = make_macros(analysis)
    lines = [
        "% Generated by paper/tools/make_mean_basis_macros.py; do not edit by hand.",
        "% Exploratory SDSD VAL16, 8 scenes, seeds 0/1; unadjusted 95% CIs; no equivalence gate.",
        "% PSNR is Y-channel dB; lower LPIPS is better. Differences are first condition minus second.",
        "% CI draws share one global RNG0; original contrast/metric order is preserved.",
        f"% analysis.json SHA256: {sha256(analysis_path)}",
        "% rank4vsidentity LPIPS effects have opposite seed signs; do not claim equivalence.",
    ]
    lines += ["\\expandafter\\def\\csname res@%s\\endcsname{%s}" % (key, macros[key])
              for key in sorted(macros)]
    content = "\n".join(lines) + "\n"
    if args.check:
        require(args.out.read_text() == content, f"Macro file differs: {args.out}")
    else:
        args.out.write_text(content)
    print(f"{'Verified' if args.check else 'Wrote'} {len(macros)} macros: {args.out}")


if __name__ == "__main__":
    main()
