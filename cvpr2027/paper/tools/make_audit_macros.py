"""Derive protocol-audit comparisons without overwriting historical results."""
from pathlib import Path
import hashlib
import json

import numpy as np

CVPR = Path(__file__).resolve().parents[2]
AUDIT = CVPR / "results" / "protocol_audit_20261111"
OLD = CVPR / "results" / "cvpr_converged" / "indomain"
MACROS = CVPR / "paper" / "tables" / "result_macros_audit.tex"
NBOOT = 10000


def load(path):
    value = json.loads(path.read_text())
    rows = {r["name"]: r for r in value["per_sequence"]}
    assert len(rows) == len(value["per_sequence"]) == 39, path
    return value, rows


def main():
    macros, report = {}, {"bootstrap_samples": NBOOT, "rng_seed": 0,
                          "unit": "paired sequence, conditional on available trained seeds",
                          "comparisons": {}}
    candidates = [
        ("random", [OLD / "e17_small_pretrained_s0.json"],
         [AUDIT / "reevaluated" / "e17_small_random_s0_saved.json"], "pretrained minus random"),
        ("grank64", [AUDIT / "reevaluated" / f"e26_grank64_s{s}_saved.json" for s in (0, 1)],
         [OLD / f"e17_small_pretrained_s{s}.json" for s in (0, 1)], "rank64 minus full-token-trained"),
        ("hybrid", [AUDIT / "reevaluated" / f"e18_hybrid_s{s}_saved.json" for s in (0, 1)],
         [OLD / f"e17_small_pretrained_s{s}.json" for s in (0, 1)], "hybrid minus per-tubelet, matched seeds 0/1"),
        ("alllayers", [AUDIT / "reevaluated" / "e18_layers_all_s2_saved.json"],
         [OLD / "e19_small_pretrained_s2.json"], "all-layers minus single-layer, seed 2; training hardware differs"),
    ]
    for tag, apaths, bpaths, interpretation in candidates:
        if not all(p.is_file() for p in apaths + bpaths):
            raise SystemExit(f"Missing required input for {tag}; no macros were written")
        a, b = [load(p) for p in apaths], [load(p) for p in bpaths]
        assert [j["seed"] for j, _ in a] == [j["seed"] for j, _ in b]
        for path, (data, _) in zip(apaths + bpaths, a + b):
            if path.parent.name == "reevaluated":
                assert data["reconstruction"]["mode"] == "saved", path
                expected = "global_rank" if tag == "grank64" else "none"
                assert data["reconstruction"]["token_proj"] == expected, path
                if tag == "grank64":
                    assert data["reconstruction"]["token_proj_k"] == 64, path
                elif tag == "random":
                    assert data["reconstruction"]["random_encoder_seed"] == 1234, path
                elif tag == "hybrid":
                    assert data["reconstruction"]["kv"] == "hybrid", path
                    assert data["reconstruction"]["layers"] == "single", path
                elif tag == "alllayers":
                    assert data["reconstruction"]["kv"] == "per_tubelet", path
                    assert data["reconstruction"]["layers"] == "all", path
        names = sorted(a[0][1])
        assert all(set(rows) == set(names) for _, rows in a + b)
        result = {"interpretation": interpretation, "seeds": [j["seed"] for j, _ in a],
                  "n": len(names), "sources": [
                      {"path": str(p.relative_to(CVPR)),
                       "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                      for p in apaths + bpaths], "metrics": {}}
        for metric, key, nd in (("psnr_y", "psnr", 3), ("lpips", "lpips", 4)):
            va = np.array([[rows[n][metric] for n in names] for _, rows in a])
            vb = np.array([[rows[n][metric] for n in names] for _, rows in b])
            assert np.isfinite(va).all() and np.isfinite(vb).all(), (tag, metric)
            d = va.mean(0) - vb.mean(0)
            idx = np.random.default_rng(0).integers(0, len(d), size=(NBOOT, len(d)))
            ci = np.percentile(d[idx].mean(1), [2.5, 97.5])
            result["metrics"][metric] = {"difference": float(d.mean()), "ci95": ci.tolist(),
                                          "a_mean": float(va.mean()), "b_mean": float(vb.mean()),
                                          "per_seed_differences": (va-vb).mean(1).tolist()}
            prefix = f"audit@{tag}@{key}"
            macros[prefix] = f"{d.mean():+.{nd}f}"
            macros[prefix + "@ci"] = "[%+.*f, %+.*f]" % (nd, ci[0], nd, ci[1])
            macros[prefix + "@a"] = f"{va.mean():.{nd}f}"
            macros[prefix + "@b"] = f"{vb.mean():.{nd}f}"
        macros[f"audit@{tag}@seeds"] = str(len(a))
        report["comparisons"][tag] = result
    if "random" not in report["comparisons"]:
        raise SystemExit("corrected random control is required; no macros were written")
    lines = ["% Generated by tools/make_audit_macros.py from separate protocol-audit JSONs."]
    lines += ["\\expandafter\\def\\csname res@%s\\endcsname{%s}" % (k, macros[k])
              for k in sorted(macros)]
    MACROS.write_text("\n".join(lines) + "\n")
    (AUDIT / "corrected_comparisons.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
